package com.dwurdy.dawnmine.topology;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

/**
 * Emits representative topology snapshots for fixed seeds into
 * {@code docs/reports/Dawnmine-0.3-topology-snapshots.txt} so reviewers can inspect
 * the actual generated plan. The file is a golden artifact: its contents are
 * fully determined by (seed, profile, bounds), so a regenerated copy that
 * differs fails the test. The rendered main path omits its terminal display
 * separator; fingerprints still cover the exact canonical plan bytes.
 */
class TopologySnapshotsTest {

    private static final Path SNAPSHOT = Path.of(
            "docs", "reports", "Dawnmine-0.3-topology-snapshots.txt");
    private static final long[] SEEDS = {42L, 1337L, 20261102L};

    private static String snapshotCanonical(TopologyPlan plan) {
        String canonical = plan.canonical();
        int mainLineEnd = canonical.indexOf('\n', canonical.indexOf("main="));
        int mainLineStart = canonical.indexOf("main=");
        if (mainLineEnd > mainLineStart && canonical.charAt(mainLineEnd - 1) == ' ') {
            return canonical.substring(0, mainLineEnd - 1) + canonical.substring(mainLineEnd);
        }
        return canonical;
    }

    private static String render() {
        TopoBounds bounds = TopologyPlannerTest.bounds(64);
        TopologyProfile profile = TopologyProfile.builtin();
        StringBuilder sb = new StringBuilder(65536);
        sb.append("# Dawnmine 0.3 topology snapshots\n");
        sb.append("# Regenerated by TopologySnapshotsTest; deterministic for (seed, profile, bounds).\n");
        sb.append("# bounds=").append(bounds).append('\n');
        for (long seed : SEEDS) {
            TopologyPlan plan = TopologyPlanner.plan(seed, profile, bounds);
            TopologyReport report = TopologyValidator.validate(plan, profile);
            sb.append("\n=== seed ").append(seed).append(" ===\n");
            sb.append("summary: ").append(plan.summary()).append('\n');
            sb.append("fingerprint: ").append(plan.fingerprint()).append('\n');
            sb.append("validation: ").append(report.ok() ? "PASS" : report.describe()).append('\n');
            sb.append(snapshotCanonical(plan));
        }
        return sb.toString();
    }

    private static String normalizeLineEndings(String text) {
        return text.replace("\r\n", "\n").replace('\r', '\n');
    }

    @Test
    void snapshotsAreStableAndWritten() throws IOException {
        String expected = render();
        // Regenerating in-process must already be identical.
        assertEquals(expected, render(), "snapshot render is not deterministic");

        if ("1".equals(System.getenv("DAWNMINE_UPDATE_SNAPSHOTS"))) {
            Files.createDirectories(SNAPSHOT.getParent());
            Files.writeString(SNAPSHOT, expected, StandardCharsets.UTF_8);
        }
        assertTrue(Files.exists(SNAPSHOT),
                "missing golden; regenerate explicitly with DAWNMINE_UPDATE_SNAPSHOTS=1");
        assertEquals(expected, normalizeLineEndings(Files.readString(SNAPSHOT, StandardCharsets.UTF_8)),
                "topology snapshot changed; regenerate explicitly and review the diff");
        assertTrue(Files.size(SNAPSHOT) > 0);
    }
}
